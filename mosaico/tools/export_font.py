#!/usr/bin/env python3
"""Export raylib's default pixel font (zlib licence, (c) Ramon Santamaria) to a C header.

Reads defaultFontData and charsWidth from raylib's src/rtext.c, unpacks the 128x128 bitmap the
way raylib's LoadFontDefault does, lays the glyphs out with its 1-pixel divisor, and writes
ASCII 32..126 as proportional glyphs: a width and 10 rows of bits (bit 0 = leftmost pixel).

usage: export_font.py <path/to/raylib/src/rtext.c> <out.h>
"""
import re
import sys
from pathlib import Path

HEIGHT, DIVISOR, SIZE, FIRST, LAST = 10, 1, 128, 32, 126


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 64
    src = Path(sys.argv[1]).read_text()
    data_text = re.search(r"defaultFontData\[512\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    data = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", data_text)]
    widths_text = re.search(r"charsWidth\[224\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    widths = [int(v) for v in re.findall(r"\d+", widths_text)]
    if len(data) != 512 or len(widths) != 224:
        raise SystemExit("unexpected rtext.c layout")

    # Bit j of word k is pixel 32*k + j (raylib: for i in steps of 32, for j 31..0).
    pixels = [False] * (SIZE * SIZE)
    for k, word in enumerate(data):
        for j in range(32):
            if word >> j & 1:
                pixels[32 * k + j] = True

    # raylib's glyph rectangles.
    recs = []
    line, pos_x, test_x = 0, DIVISOR, DIVISOR
    for i, w in enumerate(widths):
        x, y = pos_x, DIVISOR + line * (HEIGHT + DIVISOR)
        test_x += w + DIVISOR
        if test_x >= SIZE:
            line += 1
            pos_x = 2 * DIVISOR + w
            test_x = pos_x
            x, y = DIVISOR, DIVISOR + line * (HEIGHT + DIVISOR)
        else:
            pos_x = test_x
        recs.append((x, y, w))

    out = [
        "// Generated by mosaico/tools/export_font.py from raylib's default font. Do not edit.",
        "// raylib (c) 2013-2026 Ramon Santamaria, zlib licence (see THIRD_PARTY_NOTICES.md).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define PIXL_FONT_HEIGHT {HEIGHT}",
        f"#define PIXL_FONT_FIRST {FIRST}",
        f"#define PIXL_FONT_LAST {LAST}",
        "typedef struct { uint8_t width; uint16_t rows[PIXL_FONT_HEIGHT]; } pixl_glyph_t;",
        f"static const pixl_glyph_t pixl_font[{LAST - FIRST + 1}] = {{",
    ]
    for code in range(FIRST, LAST + 1):
        x, y, w = recs[code - FIRST]
        rows = []
        for r in range(HEIGHT):
            bits = 0
            for c in range(w):
                if pixels[(y + r) * SIZE + x + c]:
                    bits |= 1 << c
            rows.append(bits)
        label = chr(code).replace("\\", "backslash")
        out.append(f"    {{{w}, {{{', '.join(str(b) for b in rows)}}}}}, /* {label} */")
    out += ["};", ""]
    Path(sys.argv[2]).write_text("\n".join(out))
    print(f"wrote {LAST - FIRST + 1} glyphs to {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
