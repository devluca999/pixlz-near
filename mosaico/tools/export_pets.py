#!/usr/bin/env python3
"""Export every Pixl the Mosaico can show into one C header.

For each pet in assets/<id>/ with sprites.json and pixl.json: the common frame set as runs of one
palette colour (x, y, length, colour), drawn bottom-centred (SPEC §3.1); its palette; and what
the screen needs from pixl.json (name, movement, sticky, scale.mosaico, accent, signature name,
voice lines per event). Voice lines are reduced to ASCII for the pixel font ("…" becomes "...").

usage: export_pets.py <out.h>
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# Order = the swap carousel's order. Frogg first: he's the one who travels today.
PETS = ["frogg", "cat", "shiba", "ghost", "slugg", "widow"]
FRAMES = [
    "idle_0", "idle_1", "idle_2", "blink",
    "move_0", "move_1", "move_2",
    "poke_0", "poke_1", "poke_2",
    "grab_0", "grab_1",
    "rest_0", "rest_1", "rest_2",
    "signature_0", "signature_1", "signature_2",
    "mischief_0", "mischief_1", "mischief_2",
    "emotion_happy", "emotion_annoyed", "emotion_sleepy", "emotion_startled", "emotion_proud", "emotion_curious",
]
SOUND_EVENTS = ["greet", "happy", "curious", "annoyed", "startled", "sleepy", "sad", "idle"]
MOVEMENT = {"hop": "PIXL_MOVE_HOP", "walk": "PIXL_MOVE_WALK", "float": "PIXL_MOVE_FLOAT", "climb": "PIXL_MOVE_HOP"}
MAX_LINES = 3


def rgb(hex_colour: str) -> tuple[int, int, int]:
    h = hex_colour.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def ascii_line(text: str) -> str:
    text = text.replace("…", "...").replace("’", "'").replace("“", '"').replace("”", '"')
    return "".join(c for c in text if 32 <= ord(c) < 127)


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def runs(frame: dict, chars: str, transparent: str) -> list[tuple[int, int, int, int]]:
    out = []
    for y, row in enumerate(frame["rows"]):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == transparent:
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == ch:
                x += 1
            out.append((start, y, x - start, chars.index(ch)))
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 64
    out_path = Path(sys.argv[1])
    lines = [
        "// Generated by mosaico/tools/export_pets.py from assets/*/sprites.json and pixl.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct { uint8_t x, y, len, colour; } pixl_run_t;",
        "typedef struct { uint8_t w, h; uint16_t count; const pixl_run_t *runs; } pixl_frame_t;",
        "typedef enum { PIXL_MOVE_HOP, PIXL_MOVE_WALK, PIXL_MOVE_FLOAT } pixl_move_t;",
        "",
        "enum {",
        *[f"    PIXL_F_{name.upper()}," for name in FRAMES],
        "    PIXL_FRAME_COUNT",
        "};",
        "",
        "enum {",
        *[f"    PIXL_SOUND_{e.upper()}," for e in SOUND_EVENTS],
        "    PIXL_SOUND_COUNT",
        "};",
        f"#define PIXL_SOUND_LINES {MAX_LINES}",
        "",
        "typedef struct {",
        "    const char *id, *name, *signature;",
        "    pixl_move_t movement;",
        "    uint8_t sticky;",
        "    uint8_t scale_mosaico;          /* pixl.json scale.mosaico; 0 = the 4-pet-widths rule */",
        "    float walk_speed;               /* apx/s, walkers */",
        "    uint8_t accent[3];",
        "    uint8_t palette_count;",
        "    const uint8_t (*palette)[3];",
        "    pixl_frame_t frames[PIXL_FRAME_COUNT];",
        "    const char *sounds[PIXL_SOUND_COUNT][PIXL_SOUND_LINES]; /* NULL-padded */",
        "} pixl_pet_t;",
        "",
    ]
    table = []
    for pet in PETS:
        sprites = json.loads((ROOT / "assets" / pet / "sprites.json").read_text())
        manifest = json.loads((ROOT / "assets" / pet / "pixl.json").read_text())
        chars, palette, transparent = sprites["chars"], sprites["palette"], sprites["transparent"]
        if len(chars) != len(palette):
            raise SystemExit(f"{pet}: chars and palette differ in length")
        lines.append(f"static const uint8_t pixl_{pet}_palette[{len(palette)}][3] = {{"
                     + ", ".join("{%d,%d,%d}" % rgb(c) for c in palette) + "};")
        frame_entries = []
        for name in FRAMES:
            frame = sprites["frames"].get(name)
            if frame is None:
                raise SystemExit(f"{pet}: missing frame {name}")
            if frame["w"] > 255 or frame["h"] > 255:
                raise SystemExit(f"{pet}/{name} is too large for uint8 coordinates")
            rs = runs(frame, chars, transparent)
            ident = f"pixl_{pet}_{name}"
            body = ", ".join(f"{{{x},{y},{n},{c}}}" for x, y, n, c in rs)
            lines.append(f"static const pixl_run_t {ident}[{max(len(rs), 1)}] = {{{body or '{0,0,0,0}'}}};")
            frame_entries.append(f"{{{frame['w']}, {frame['h']}, {len(rs)}, {ident}}}")
        ui = manifest.get("ui", {})
        sounds = ui.get("sounds", {})
        sound_rows = []
        for event in SOUND_EVENTS:
            picked = [ascii_line(t) for t in sounds.get(event, [])][:MAX_LINES]
            picked = [t for t in picked if t]
            cells = [c_string(t) for t in picked] + ["0"] * (MAX_LINES - len(picked))
            sound_rows.append("{" + ", ".join(cells) + "}")
        physics = manifest.get("physics", {})
        scale = int((manifest.get("scale") or {}).get("mosaico", 0))
        accent = rgb(ui.get("accent", "#FFFFFF"))
        table.append("    {" + ", ".join([
            c_string(pet), c_string(ascii_line(manifest.get("name", pet))),
            c_string(ascii_line(ui.get("signature", "Trick"))),
            MOVEMENT.get(manifest.get("movement", "hop"), "PIXL_MOVE_HOP"),
            "1" if manifest.get("sticky") else "0", str(scale),
            f"{float(physics.get('walkSpeed', 0)):.1f}f",
            "{%d,%d,%d}" % accent, str(len(palette)), f"pixl_{pet}_palette",
            "{" + ", ".join(frame_entries) + "}",
            "{" + ", ".join(sound_rows) + "}",
        ]) + "},")
        lines.append("")
    lines += [f"#define PIXL_PET_COUNT {len(PETS)}",
              "static const pixl_pet_t pixl_pets[PIXL_PET_COUNT] = {", *table, "};", ""]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    print(f"wrote {len(PETS)} pets x {len(FRAMES)} frames to {out_path} ({out_path.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
