#!/usr/bin/env python3
"""Export a Pixl's frames from assets/<pet>/sprites.json to a C header for the Mosaico.

Each frame becomes horizontal runs of one palette colour (x, y, length, colour), drawn
bottom-centred: the frame's bottom row is the feet, centred on the Pixl's spot (SPEC §3.1).

usage: export_sprites.py <pet> <out.h> [frame ...]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_FRAMES = ["idle_0", "idle_1", "idle_2", "blink", "move_0", "move_1", "move_2", "emotion_annoyed"]


def rgb(hex_colour: str) -> tuple[int, int, int]:
    h = hex_colour.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def runs(frame: dict, chars: str, transparent: str) -> list[tuple[int, int, int, int]]:
    out = []
    for y, row in enumerate(frame["rows"]):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == transparent:
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == ch:
                x += 1
            out.append((start, y, x - start, chars.index(ch)))
    return out


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 64
    pet, out_path = sys.argv[1], Path(sys.argv[2])
    names = sys.argv[3:] or DEFAULT_FRAMES
    data = json.loads((ROOT / "assets" / pet / "sprites.json").read_text())
    chars, palette, transparent = data["chars"], data["palette"], data["transparent"]
    if len(chars) != len(palette):
        raise SystemExit("chars and palette differ in length")
    sym = pet.upper()
    manifest = json.loads((ROOT / "assets" / pet / "pixl.json").read_text())
    scale_override = int((manifest.get("scale") or {}).get("mosaico", 0))

    lines = [
        f"// Generated by mosaico/tools/export_sprites.py from assets/{pet}/sprites.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct { uint8_t x, y, len, colour; } pixl_run_t;",
        "typedef struct { uint8_t w, h; uint16_t count; const pixl_run_t *runs; } pixl_frame_t;",
        "",
        f"static const uint8_t {pet}_palette[{len(palette)}][3] = {{"
        + ", ".join("{%d,%d,%d}" % rgb(c) for c in palette) + "};",
        "",
        "/* pixl.json scale.mosaico; 0 = use the 4-pet-widths rule (SPEC §12.2). */",
        f"#define {sym}_SCALE_MOSAICO {scale_override}",
        "",
    ]
    enum = []
    table = []
    for name in names:
        frame = data["frames"][name]
        if frame["w"] > 255 or frame["h"] > 255:
            raise SystemExit(f"{name} is too large for uint8 coordinates")
        rs = runs(frame, chars, transparent)
        ident = f"{pet}_{name}"
        body = ", ".join(f"{{{x},{y},{n},{c}}}" for x, y, n, c in rs)
        lines.append(f"static const pixl_run_t {ident}_runs[{len(rs)}] = {{{body}}};")
        enum.append(f"    {sym}_{name.upper()},")
        table.append(f"    {{{frame['w']}, {frame['h']}, {len(rs)}, {ident}_runs}},")
    lines += ["", "enum {", *enum, f"    {sym}_FRAME_COUNT", "};", "",
              f"static const pixl_frame_t {pet}_frames[{sym}_FRAME_COUNT] = {{", *table, "};", ""]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines))
    print(f"wrote {len(names)} frames to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
