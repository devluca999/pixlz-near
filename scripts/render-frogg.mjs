// Renders Frogg's frames from the Claude Design C7 engine (design/explorations/c3, baseline)
// into indexed-colour JSON for the Mac app. No canvas, no PNGs: the engine's render() is
// pure, and the repo keeps PNGs in Git LFS. Poses are the ones used in the C7 behavior
// and emotion sheets.
//
//   node scripts/render-frogg.mjs --swift > macos/PixlMemory/Sources/PixlMemoryKit/FroggSpriteData.swift
//   node scripts/render-frogg.mjs           (plain JSON)
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = fileURLToPath(new URL("../design/explorations/c3/", import.meta.url));
const ctx = { console, Math, Object, Array, Uint8Array, Float32Array, Number, String, JSON, parseInt, isNaN, Infinity };
ctx.window = ctx;
ctx.document = { createElement() { throw new Error("DOM not available in the exporter"); } };
vm.createContext(ctx);
for (const f of ["engine.js", "pets-a.js", "pets-b.js", "pets-d.js", "pets-f.js", "pets-g.js", "behavior.js", "pets-h.js"]) {
  vm.runInContext(readFileSync(root + f, "utf8"), ctx, { filename: f });
}
const { pets, render, cropBox } = ctx.PX3;
const frogg = pets.frogg;
const fr = (o) => Object.assign({ v: "F" }, o);

// name → pose. Behavior poses from C7 sheets (behavior.js), emotions from PX3.emotions.frogg.
const poses = {
  idle_0: fr({ eyes: "half", mouth: "line" }),
  idle_1: fr({ eyes: "closed", head: { rot: 5 } }),
  idle_2: fr({ eyes: "smug", throat: 0.7, head: { dy: -1 } }),
  move_0: "coiled",
  move_1: "hop",
  move_2: { v: "side", rot: 9 },
  poke_0: fr({ eyes: "low", head: { dy: 3, rot: -5 } }),
  poke_1: fr({ eyes: "half", look: [1.4, -1.4], head: { rot: -8 } }),
  poke_2: fr({ eyes: "smug", throat: 1, mouth: "smile", head: { dy: -2, rot: -3 } }),
  rest_1: "sleep",
};
for (const [label, pose] of ctx.PX3.emotions.frogg) poses["emotion_" + label.toLowerCase()] = pose;

const palette = [];
const index = new Map();
const CHARS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ!#$%&()*+,-/:;<=>?@[]^_{|}~";
const frames = {};
for (const [name, pose] of Object.entries(poses)) {
  const spr = Object.assign(frogg.build(pose), { shadow: null });
  const r = render(spr, frogg.pal, { rim: frogg.rim, rimTop: frogg.rimTop });
  const [x0, y0, x1, y1] = cropBox(r, spr);
  const rows = [];
  for (let y = y0; y <= y1; y++) {
    let row = "";
    for (let x = x0; x <= x1; x++) {
      const g = r.G[y * r.W + x];
      if (!g) { row += "."; continue; }
      if (!index.has(g.c)) {
        if (palette.length >= CHARS.length) throw new Error("palette too large");
        index.set(g.c, CHARS[palette.length]);
        palette.push(g.c);
      }
      row += index.get(g.c);
    }
    rows.push(row);
  }
  // cropBox pads one transparent pixel on each side; trim it so the feet are the bottom row.
  while (rows.length && /^\.+$/.test(rows[0])) rows.shift();
  while (rows.length && /^\.+$/.test(rows[rows.length - 1])) rows.pop();
  const opaqueCol = (i) => rows.some((r) => r[i] !== ".");
  let left = 0, right = rows[0].length - 1;
  while (!opaqueCol(left)) left++;
  while (!opaqueCol(right)) right--;
  const trimmed = rows.map((r) => r.slice(left, right + 1));
  frames[name] = { w: right - left + 1, h: trimmed.length, rows: trimmed };
}

const json = JSON.stringify({
  source: "design/explorations/c3 (Claude Design C7), rendered by scripts/render-frogg.mjs",
  transparent: ".",
  chars: CHARS.slice(0, palette.length),
  palette,
  frames,
}, null, 1);
if (process.argv.includes("--swift")) {
  if (json.includes('"##')) throw new Error("JSON would end the Swift raw string");
  process.stdout.write(`// Generated by scripts/render-frogg.mjs from the Claude Design C7 engine. Do not edit.\n` +
    `// Indexed-colour frames as JSON text: no PNGs (the repo keeps PNGs in Git LFS).\n\n` +
    `let froggSpriteJSON = ##"""\n${json}\n"""##\n`);
} else {
  process.stdout.write(json + "\n");
}
